hu_state_us <- hu_state_us |> mutate(across(where(is.character), stringi::stri_enc_tonative))

hu_state_us <- hu_state_us[!is.na(state_code), ]

dbWriteTable(conh, "hu_state_us", hu_state_us, overwrite = TRUE)

